/**
 * Échappe du texte destiné au HTML.
 * @param {*} value Texte brut.
 * @return {string} Texte échappé.
 */
function escapeEmailText(value) {
  return String(value == null ? "" : value)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#39;");
}

/**
 * Donne une version HTML aux emails auparavant uniquement textuels.
 * @param {string} text Message original.
 * @return {string} Contenu HTML.
 */
function textToEmailHtml(text) {
  const escaped = escapeEmailText(text);
  const linked = escaped.replace(/https?:\/\/[^\s<>]+/g, (url) =>
    `<a href="${url}" style="color:#1e3a8a;">${url}</a>`,
  );
  return linked.split(/\r?\n\s*\r?\n/).map((paragraph) =>
    `<p style="margin:0 0 18px;">` +
    paragraph.replace(/\r?\n/g, "<br>") + "</p>",
  ).join("\n");
}

