/**
 * Conserve destinataires, texte, liens métier et pièces jointes du message.
 * @param {Object} options Options Nodemailer du message métier.
 * @return {Object} Message habillé et images intégrées.
 */
function buildSphotMessage(options) {
  const body = typeof options.html === "string" ?
    options.html : textToEmailHtml(options.text || "");
  return {
    ...options,
    html: renderSphotEmail(body),
    attachments: [
      ...(options.attachments || []),
      {
        filename: "sphot_title.png",
        cid: LOGO_CID,
        content: Buffer.from(LOGO_PNG_BASE64, "base64"),
        contentType: "image/png",
        contentDisposition: "inline",
      },
      {
        filename: "fire_red_icon.png",
        cid: FIRE_PNG_CID,
        content: Buffer.from(FIRE_PNG_BASE64, "base64"),
        contentType: "image/png",
        contentDisposition: "inline",
      },
    ],
  };
}

/**
 * Point d'envoi unique à utiliser pour tous les emails SPHOT.
 * @param {Object} transporter Transporteur Nodemailer existant.
 * @param {Object} options Message métier.
 * @return {Promise<Object>} Résultat de l'envoi, sans masquer ses erreurs.
 */
function sendSphotMail(transporter, options) {
  return transporter.sendMail(buildSphotMessage(options));
}

module.exports = {sendSphotMail, buildSphotMessage};
